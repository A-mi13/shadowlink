// Плановые ротации как ВТОРАЯ, отдельная выборка (2026-08-12).
//
// Почему это понадобилось. До сих пор Record вызывался из единственного места —
// ветки ошибки чтения в ws_pool.go, — поэтому выборка была цензурирована: слоты,
// снятые НАШЕЙ собственной ротацией, в неё не попадали. Два следствия были
// известны и задокументированы в шапке пакета, но третье вылезло только в поле.
//
// Полевой разбор 20260812-110200 (1ч58м) показал цену:
//
//   - 8 наблюдений о резе против порога MinSamplesForInference=12, поэтому
//     logSlotDeathSummary молчал ВЕСЬ прогон, а вместе с ним молчал и
//     ageAdapter.Observe — адаптация порога не исполнялась ни секунды;
//   - обратная связь отрицательная: чем лучше работает плановый дренаж, тем
//     меньше резов, тем слепее контур. Улучшение дренажа (фикс фантомного
//     счётчика 2026-08-11) срезало резы с 10.2/ч до 4.1/ч и тем самым добило
//     наблюдаемость;
//   - без знаменателя перцентили по резам вводят в заблуждение: p50 по 7 точкам
//     дал 85.0с против 97.6с по 222 точкам, и это было прочитано как «окно
//     сжалось». Фактически ни одно соединение в том прогоне не жило дольше
//     104.5с — посредник физически не мог показать рез на 110с. Классический
//     survivorship bias: измерен собственный порог ротации, а не цензор.
//
// Почему ОТДЕЛЬНЫЙ ринг, а не метка CloseKind в общем. Соотношение событий в
// поле — 740 плановых против 8 резов (~92:1). В общем ринге на 512 записей
// плановые вытеснили бы все наблюдения о резе за ~20 минут, и Summarize стал бы
// описывать наш собственный порог вместо поведения посредника. Молчание видно;
// подмена данных — нет. Поэтому Summarize и Infer работают ТОЛЬКО по рингу
// резов и этой правкой не затронуты вовсе.
//
// Что даёт второй ринг: знаменатель. Появляются две величины, которые skill
// прямо называет невыводимыми из цензурированной выборки, — доля «срезано
// посредником» (CutShare) и hazard-кривая (Hazard), то есть риск реза среди
// ДОЖИВШИХ до полосы возраста. Hazard устойчив к survivorship bias по
// построению: он делит на число дошедших, а не на размер выборки.

// ClosePlannedRotation — метка close-kind для слота, снятого нашей собственной
// плановой ротацией (не резом посредника).
//
// Заведена в вокабуляре close-kind, а не отдельным bool, чтобы filterNoise мог
// отбросить такое наблюдение, даже если оно ошибочно попадёт в ринг резов:
// перепутать Record и RecordPlanned на вызывающей стороне легко, а цена ошибки —
// порог ротации, выведенный из самого себя.
const ClosePlannedRotation = "planned_rotation"

// RecordPlanned сохраняет наблюдение о ПЛАНОВОЙ смене слота в отдельный ринг.
//
// CloseKind проставляется здесь принудительно: вызывающему незачем знать метку,
// а расхождение между «положили в ринг плановых» и «пометили как плановую»
// породило бы ровно ту двойную правду, от которой лечится этот пакет.
func (r *Recorder) RecordPlanned(o Observation) {
	o.CloseKind = ClosePlannedRotation
	r.mu.Lock()
	defer r.mu.Unlock()
	if len(r.planned) == 0 {
		// Ёмкость берём у ринга резов, но с фолбэком: у нулевого Recorder
		// (`&Recorder{}` — sync.Mutex делает такое значение внешне пригодным)
		// len(r.buf)==0, и make([]Observation, 0) дал бы панику index out of
		// range на первой же записи. Ревью 2026-08-12: экспортируемого способа
		// получить такой Recorder нет (NewRecorder нормализует capacity<=0), но
		// ленивая инициализация ВЫГЛЯДЕЛА защитой, не будучи ею.
		capacity := len(r.buf)
		if capacity == 0 {
			capacity = DefaultCapacity
		}
		r.planned = make([]Observation, capacity)
	}
	r.planned[r.plannedNext] = o
	r.plannedNext = (r.plannedNext + 1) % len(r.planned)
	if r.plannedCount < len(r.planned) {
		r.plannedCount++
	}
	r.plannedTotal++
}

// LenPlanned возвращает число плановых наблюдений в ринге.
func (r *Recorder) LenPlanned() int {
	r.mu.Lock()
	defer r.mu.Unlock()
	return r.plannedCount
}

// TotalPlanned возвращает пожизненное число плановых ротаций, включая затёртые.
// Отдельно от LenPlanned: иначе «сколько ротаций было» не отличить от «сколько
// влезло в ринг».
func (r *Recorder) TotalPlanned() uint64 {
	r.mu.Lock()
	defer r.mu.Unlock()
	return r.plannedTotal
}

// snapshotPlanned — копия плановых наблюдений, oldest first. nil когда пусто.
func (r *Recorder) snapshotPlanned() []Observation {
	r.mu.Lock()
	defer r.mu.Unlock()
	if r.plannedCount == 0 {
		return nil
	}
	out := make([]Observation, 0, r.plannedCount)
	start := 0
	if r.plannedCount == len(r.planned) {
		start = r.plannedNext
	}
	for i := 0; i < r.plannedCount; i++ {
		out = append(out, r.planned[(start+i)%len(r.planned)])
	}
	return out
}

// HazardBand — риск реза в полосе возраста: сколько соединений ДОШЛО до нижней
// границы полосы и сколько из них было срезано внутри неё.
//
// Смысл именно в знаменателе. Гистограмма смертей отвечает на вопрос «где
// умирают», и ответ на него смещён нашей же политикой ротации. Hazard отвечает
// на вопрос «каков риск, если дожил», и от политики он зависит слабее — но
// только при корректном учёте цензурирования, см. CensoredIn.
type HazardBand struct {
	// FromMs, ToMs — границы полосы возраста, [From, To).
	FromMs, ToMs int64
	// Reached — сколько соединений (любого исхода) дожило до FromMs. Сырое
	// число, публикуется для наблюдаемости; в Rate идёт с поправкой.
	Reached int
	// CensoredIn — сколько из дошедших снято НАМИ (плановая ротация) внутри
	// полосы, то есть прожило её лишь частично.
	//
	// Первая версия этого кода (2026-08-12) считала такие наблюдения
	// полноценными «дожившими» и тем ЗАНИЖАЛА риск. Ревью того же дня показало
	// цену на данных, повторяющих поле — 100 плановых равномерно 80–90с и 5
	// резов: наивный расчёт давал 0.0476 против actuarial 0.0909, занижение в
	// 1.91 раза. Причём занижение в той самой полосе, где ищется порог: в поле
	// плановые режутся на p50≈81с, то есть массово внутри первых полос.
	//
	// По памяти проекта «занижение хуже завышения»: читатель решил бы, что риск
	// на 80–90с приемлем и порог сжимать не надо.
	CensoredIn int
	// Cut — сколько из дошедших срезано посредником внутри полосы.
	Cut int

	// ExposureMs — суммарное время, фактически проведённое наблюдениями ВНУТРИ
	// полосы: Σ min(age, To) − From по всем, кто дожил до From. Точная величина
	// «человеко-секунд под риском», без предположений о том, где внутри полосы
	// оказалось цензурирование.
	//
	// Заведено 2026-08-14, потому что actuarial-вес 1/2 в Rate() оказался
	// неверен именно в нашей конфигурации — см. RateByExposure.
	ExposureMs int64

	// RingSaturated — хотя бы один из рингов заполнен целиком, то есть старые
	// наблюдения уже затираются. Числитель и знаменатель после этого набираются
	// из окон РАЗНОЙ длины, и любая доля смещается.
	//
	// Замер PROBE 2026-08-13 (nixavpn-PROBE-20260813-121747): плановых 1256 при
	// ёмкости ринга 512 (переполнен), резов 126 (нет). Числитель полный,
	// знаменатель обрезан последними 512 → логировалось rate=0.0367 против
	// 0.0178 по экспозиции, ЗАВЫШЕНИЕ ×2.06.
	//
	// CutShare про эту ловушку предупреждает документацией (cut_share_ring vs
	// cut_share_lifetime), а Hazard не предупреждал вовсе, хотя болезнь та же.
	// Поле сделано явным, чтобы искажение было видно в логе, а не выводилось
	// читателем из третьих чисел.
	RingSaturated bool
}

// RateByExposure — риск реза на единицу времени в полосе, 1/с.
//
// ЕДИНСТВЕННАЯ форма, не требующая предположений о распределении цензурирования
// внутри полосы: делим число резов на фактически прожитое в полосе время.
//
// # Почему пришлось заводить вторую метрику (разбор 2026-08-14)
//
// Rate() применяет actuarial-поправку: цензурированные внутри полосы входят с
// весом 1/2, «потому что прожили в среднем половину полосы». Предположение
// верно, когда цензурирование распределено внутри полосы равномерно. В нашей
// конфигурации оно НЕ равномерно и сидит у самой НИЖНЕЙ кромки: порог ротации
// стоит на 70s + stagger, то есть массовая плановая смерть приходится на
// 74-80s, а полоса начинается с 80s. Восстановленные времена жизни (622
// ротации, лог nixavpn-DEBUG-20260813-153638): p75 = p90 = 80.2s. То есть
// цензурированные проживают в полосе 80-85s около 0.2s, а не 2.5s — вес 1/2
// завышает знаменатель в ~12 раз по этой группе.
//
// Цена на данных того же прогона: логируемый Rate() дал 3.37% для полосы 80-85s
// против 6.94% по экспозиции — ЗАНИЖЕНИЕ ВДВОЕ ровно в той полосе, где ищется
// порог ротации. По памяти проекта «занижение хуже завышения»: читатель решил
// бы, что риск на 80-85s приемлем и сжимать порог не надо.
//
// Комментарий у CensoredIn предупреждает про занижение при НАИВНОМ расчёте
// (вес 1) и был прав; чего он не знал — что actuarial-поправка даёт то же
// занижение, когда цензура сконцентрирована у нижней кромки.
//
// # Как читать
//
// Величина — интенсивность (1/с), а не вероятность. Вероятность реза при
// проходе полосы целиком ≈ 1 − exp(−rate × ширина_полосы); для малых значений
// просто rate × ширина. Ноль при пустой экспозиции — «нет данных», НЕ «нет
// риска», различать обязан вызывающий по ExposureMs.
func (h HazardBand) RateByExposure() float64 {
	if h.ExposureMs <= 0 {
		return 0
	}
	return float64(h.Cut) / (float64(h.ExposureMs) / 1000)
}

// Rate — доля срезанных среди эффективного числа под риском.
//
// Знаменатель — actuarial (он же Kaplan-Meier для сгруппированных интервалов):
// цензурированные внутри полосы входят с весом 1/2, потому что прожили в
// среднем половину полосы. Без поправки знаменатель раздут теми, кто полосу не
// прожил, и риск занижен (см. CensoredIn).
//
// Ноль при пустой полосе — это «нет данных», а НЕ «нулевой риск». Различать
// обязан вызывающий по полю Reached; отдельного sentinel-значения нет намеренно,
// чтобы величину нельзя было случайно усреднить с настоящими нулями.
//
// ⚠ СМЕЩЕНА В НАШЕЙ КОНФИГУРАЦИИ, замер 2026-08-14: вес 1/2 предполагает
// равномерное цензурирование внутри полосы, а у нас оно сидит у нижней кромки
// (порог ротации 70s+stagger → плановые умирают на 74-80s, полоса начинается с
// 80s, проживают в ней ~0.2s вместо 2.5s). Занижает вдвое ровно в той полосе,
// где ищется порог. Оставлена для сравнимости с прежними логами; решения
// принимать по RateByExposure, см. обоснование там.
func (h HazardBand) Rate() float64 {
	if h.Reached == 0 {
		return 0
	}
	eff := float64(h.Reached) - 0.5*float64(h.CensoredIn)
	if eff <= 0 {
		return 0
	}
	return float64(h.Cut) / eff
}

// Hazard считает риск реза в полосе [fromMs, toMs).
//
// Учитываются оба ринга: плановые дают выживших, резы — события. Наблюдение
// попадает в знаменатель, если его возраст >= fromMs (то есть оно дожило до
// полосы), и в числитель — если это рез и его возраст внутри полосы.
//
// Заодно копится ExposureMs — фактически прожитое в полосе время, из которого
// считается несмещённый RateByExposure. Считается здесь, а не в HazardBand,
// потому что для него нужны сами возрасты, а не агрегаты.
func (r *Recorder) Hazard(fromMs, toMs int64) HazardBand {
	h := HazardBand{FromMs: fromMs, ToMs: toMs}
	// Насыщение любого из рингов делает окна наблюдения разными по длине, и
	// ЛЮБАЯ доля после этого смещена — включая RateByExposure, у которого
	// обрезается знаменатель. Проверяем ДО обхода: сравнение длины с ёмкостью.
	// В PROBE 2026-08-13 это дало завышение ×2.06 и было принято за реальный
	// рост риска (см. HazardBand.RingSaturated).
	r.mu.Lock()
	h.RingSaturated = (len(r.planned) > 0 && r.plannedCount == len(r.planned)) ||
		(len(r.buf) > 0 && r.count == len(r.buf))
	r.mu.Unlock()

	// exposure — сколько времени наблюдение прожило ВНУТРИ полосы. Для дожившего
	// до конца это вся ширина; для умершего внутри — от нижней кромки до смерти.
	// Именно эта величина, а не «половина полосы по предположению», делает
	// знаменатель честным при цензурировании у кромки.
	exposure := func(ageMs int64) int64 {
		end := ageMs
		if end > toMs {
			end = toMs
		}
		return end - fromMs
	}

	for _, o := range r.Snapshot() {
		if o.AgeMs < fromMs {
			continue
		}
		h.Reached++
		h.ExposureMs += exposure(o.AgeMs)
		if o.AgeMs < toMs {
			h.Cut++
		}
	}
	for _, o := range r.snapshotPlanned() {
		if o.AgeMs < fromMs {
			continue
		}
		h.Reached++
		h.ExposureMs += exposure(o.AgeMs)
		if o.AgeMs < toMs {
			// Сняли МЫ, не дав прожить полосу до конца — цензурирование справа.
			// В Rate войдёт с весом 1/2 (смещает, см. Rate), в ExposureMs —
			// ровно тем временем, что прожило.
			h.CensoredIn++
		}
	}
	return h
}

// CutShare — доля слотов, снятых посредником, от всех наблюдённых смен слота.
// Возвращает долю и общее число наблюдений.
//
// Именно эту величину шапка пакета объявляла невыводимой («ByCloseKind cannot
// yield what fraction of slots the censor cut — planned rotations are absent
// from the denominator by construction»). С отдельным рингом знаменатель есть.
//
// ⚠ Ограничение остаётся: оба ринга конечны и переполняются независимо, поэтому
// при разной скорости заполнения доля смещается в сторону более редкого события.
// Для абсолютного счёта надо брать Total()/TotalPlanned(), которые не забывают.
func (r *Recorder) CutShare() (share float64, total int) {
	cuts := r.Len()
	planned := r.LenPlanned()
	total = cuts + planned
	if total == 0 {
		return 0, 0
	}
	return float64(cuts) / float64(total), total
}
