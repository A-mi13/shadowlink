package slotobs

// Плановые ротации как ВТОРАЯ, отдельная выборка (2026-08-12).
//
// Почему это понадобилось. До сих пор Record вызывался из единственного места —
// ветки ошибки чтения в ws_pool.go, — поэтому выборка была цензурирована: слоты,
// снятые НАШЕЙ собственной ротацией, в неё не попадали. Два следствия были
// известны и задокументированы в шапке пакета, но третье вылезло только в поле.
//
// Полевой разбор 20260812-110200 (1ч58м) показал цену:
//
//   - 8 наблюдений о резе против порога MinSamplesForInference=12, поэтому
//     logSlotDeathSummary молчал ВЕСЬ прогон, а вместе с ним молчал и
//     ageAdapter.Observe — адаптация порога не исполнялась ни секунды;
//   - обратная связь отрицательная: чем лучше работает плановый дренаж, тем
//     меньше резов, тем слепее контур. Улучшение дренажа (фикс фантомного
//     счётчика 2026-08-11) срезало резы с 10.2/ч до 4.1/ч и тем самым добило
//     наблюдаемость;
//   - без знаменателя перцентили по резам вводят в заблуждение: p50 по 7 точкам
//     дал 85.0с против 97.6с по 222 точкам, и это было прочитано как «окно
//     сжалось». Фактически ни одно соединение в том прогоне не жило дольше
//     104.5с — посредник физически не мог показать рез на 110с. Классический
//     survivorship bias: измерен собственный порог ротации, а не цензор.
//
// Почему ОТДЕЛЬНЫЙ ринг, а не метка CloseKind в общем. Соотношение событий в
// поле — 740 плановых против 8 резов (~92:1). В общем ринге на 512 записей
// плановые вытеснили бы все наблюдения о резе за ~20 минут, и Summarize стал бы
// описывать наш собственный порог вместо поведения посредника. Молчание видно;
// подмена данных — нет. Поэтому Summarize и Infer работают ТОЛЬКО по рингу
// резов и этой правкой не затронуты вовсе.
//
// Что даёт второй ринг: знаменатель. Появляются две величины, которые skill
// прямо называет невыводимыми из цензурированной выборки, — доля «срезано
// посредником» (CutShare) и hazard-кривая (Hazard), то есть риск реза среди
// ДОЖИВШИХ до полосы возраста. Hazard устойчив к survivorship bias по
// построению: он делит на число дошедших, а не на размер выборки.

// ClosePlannedRotation — метка close-kind для слота, снятого нашей собственной
// плановой ротацией (не резом посредника).
//
// Заведена в вокабуляре close-kind, а не отдельным bool, чтобы filterNoise мог
// отбросить такое наблюдение, даже если оно ошибочно попадёт в ринг резов:
// перепутать Record и RecordPlanned на вызывающей стороне легко, а цена ошибки —
// порог ротации, выведенный из самого себя.
const ClosePlannedRotation = "planned_rotation"

// RecordPlanned сохраняет наблюдение о ПЛАНОВОЙ смене слота в отдельный ринг.
//
// CloseKind проставляется здесь принудительно: вызывающему незачем знать метку,
// а расхождение между «положили в ринг плановых» и «пометили как плановую»
// породило бы ровно ту двойную правду, от которой лечится этот пакет.
func (r *Recorder) RecordPlanned(o Observation) {
	o.CloseKind = ClosePlannedRotation
	r.mu.Lock()
	defer r.mu.Unlock()
	if r.planned == nil {
		r.planned = make([]Observation, len(r.buf))
	}
	r.planned[r.plannedNext] = o
	r.plannedNext = (r.plannedNext + 1) % len(r.planned)
	if r.plannedCount < len(r.planned) {
		r.plannedCount++
	}
	r.plannedTotal++
}

// LenPlanned возвращает число плановых наблюдений в ринге.
func (r *Recorder) LenPlanned() int {
	r.mu.Lock()
	defer r.mu.Unlock()
	return r.plannedCount
}

// TotalPlanned возвращает пожизненное число плановых ротаций, включая затёртые.
// Отдельно от LenPlanned: иначе «сколько ротаций было» не отличить от «сколько
// влезло в ринг».
func (r *Recorder) TotalPlanned() uint64 {
	r.mu.Lock()
	defer r.mu.Unlock()
	return r.plannedTotal
}

// snapshotPlanned — копия плановых наблюдений, oldest first. nil когда пусто.
func (r *Recorder) snapshotPlanned() []Observation {
	r.mu.Lock()
	defer r.mu.Unlock()
	if r.plannedCount == 0 {
		return nil
	}
	out := make([]Observation, 0, r.plannedCount)
	start := 0
	if r.plannedCount == len(r.planned) {
		start = r.plannedNext
	}
	for i := 0; i < r.plannedCount; i++ {
		out = append(out, r.planned[(start+i)%len(r.planned)])
	}
	return out
}

// HazardBand — риск реза в полосе возраста: сколько соединений ДОШЛО до нижней
// границы полосы и сколько из них было срезано внутри неё.
//
// Смысл именно в знаменателе. Гистограмма смертей отвечает на вопрос «где
// умирают», и ответ на него смещён нашей же политикой ротации. Hazard отвечает
// на вопрос «каков риск, если дожил», и он от политики не зависит: слоты,
// снятые плановой ротацией до полосы, в знаменатель не попадают, а снятые
// внутри полосы — попадают, потому что риск они реально прожили.
type HazardBand struct {
	// FromMs, ToMs — границы полосы возраста, [From, To).
	FromMs, ToMs int64
	// Reached — сколько соединений (любого исхода) дожило до FromMs.
	Reached int
	// Cut — сколько из них срезано посредником внутри полосы.
	Cut int
}

// Rate — доля срезанных среди доживших. 0 при пустой полосе.
//
// Ноль при Reached==0 — это «нет данных», а НЕ «нулевой риск». Различать обязан
// вызывающий по полю Reached; отдельного sentinel-значения нет намеренно, чтобы
// величину нельзя было случайно усреднить с настоящими нулями.
func (h HazardBand) Rate() float64 {
	if h.Reached == 0 {
		return 0
	}
	return float64(h.Cut) / float64(h.Reached)
}

// Hazard считает риск реза в полосе [fromMs, toMs).
//
// Учитываются оба ринга: плановые дают выживших, резы — события. Наблюдение
// попадает в знаменатель, если его возраст >= fromMs (то есть оно дожило до
// полосы), и в числитель — если это рез и его возраст внутри полосы.
func (r *Recorder) Hazard(fromMs, toMs int64) HazardBand {
	h := HazardBand{FromMs: fromMs, ToMs: toMs}
	for _, o := range r.Snapshot() {
		if o.AgeMs < fromMs {
			continue
		}
		h.Reached++
		if o.AgeMs < toMs {
			h.Cut++
		}
	}
	for _, o := range r.snapshotPlanned() {
		if o.AgeMs >= fromMs {
			h.Reached++
		}
	}
	return h
}

// CutShare — доля слотов, снятых посредником, от всех наблюдённых смен слота.
// Возвращает долю и общее число наблюдений.
//
// Именно эту величину шапка пакета объявляла невыводимой («ByCloseKind cannot
// yield what fraction of slots the censor cut — planned rotations are absent
// from the denominator by construction»). С отдельным рингом знаменатель есть.
//
// ⚠ Ограничение остаётся: оба ринга конечны и переполняются независимо, поэтому
// при разной скорости заполнения доля смещается в сторону более редкого события.
// Для абсолютного счёта надо брать Total()/TotalPlanned(), которые не забывают.
func (r *Recorder) CutShare() (share float64, total int) {
	cuts := r.Len()
	planned := r.LenPlanned()
	total = cuts + planned
	if total == 0 {
		return 0, 0
	}
	return float64(cuts) / float64(total), total
}
