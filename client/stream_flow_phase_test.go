// Фаза отправок credit-sender'а: WINDOW_UPDATE — это РЕАЛЬНЫЕ байты на wire
// (uplink-фрейм к origin), поэтому период их отправки виден цензору.
//
// История дефекта и его лечения:
//  1. расписание задавал time.NewTicker(8ms). Джиттер в цикле был, но приложен
//     к ПОРОГУ (thresholdRatio 0.4-0.6), а не к периоду пробуждения — тот же
//     дефект, что ловили на rotationWatchdogTick: «джиттер к порогу не
//     размазывает фазу, она квантуется тиком проверки» (CLAUDE.md hard rule 9);
//  2. свойство кода замерено 2026-08-18: R@8мс ≈ 0.95-0.99 внутри процесса;
//  3. НАБЛЮДАЕМОСТЬ подтверждена на проводе 2026-08-19 (pcap, pktmon, 1.6 млн
//     кадров): uplink payload 71 Б → R@8мс = 0.9445 при n=21 991, при том что
//     соседние размеры (75/65/99 Б) чисты. 71 Б = 6 Б WINDOW_UPDATE + AES-GCM +
//     WS-фрейм + TCP/IP;
//  4. исправлено: time.Timer с перевзводом на nextCreditSenderWakeup()
//     (tick + uniform[0, tick)), константа 8 мс НЕ менялась (hard rule 8).
//
// Тесты ниже разделены по смыслу: ..._JitteredWakeupBreaksGrid отвечает за
// ФАЗУ (R + слепой скан + отсутствие credit-stall), ..._WakeupIsNotAFixedTicker
// — за ИСТОЧНИК (интервалы различаются, в коде нет NewTicker).
//
// ⚠ Пару нужно читать ВМЕСТЕ: по отдельности каждый имеет дыру. Замер порчами
// 2026-09-01 (методика и цифры — в докстринге ..._JitteredWakeupBreaksGrid):
//
//	порча                                   Grid   NotAFixedTicker
//	time.NewTicker вместо Timer+Reset       FAIL   FAIL
//	nextCreditSenderWakeup без джиттера     PASS   FAIL
//	отправки гонит только watchdog 200 мс   FAIL   FAIL
//
// То есть возврат к фиксированному периоду ловит ТОЛЬКО второй тест, и удалять
// его как «дублирующий фазовый» нельзя.
//
// ⚠ Прежние тесты creditSender этого поймать не могли: они зовут
// creditSenderTick напрямую, минуя таймер, то есть проверяют решение «слать
// или нет», а не момент отправки.

// vectorStrengthPhase — длина среднего вектора фаз для моментов ts (в
// секундах), свёрнутых по периоду period. R=1 — идеальная решётка,
// R~1/sqrt(n) — равномерная фаза. Дубликат величины из tools/firstpackets
// намеренный: инструмент — отдельный main-пакет, тянуть его в client нельзя.
func vectorStrengthPhase(ts []float64, period float64) float64 {
	if len(ts) < 2 || period <= 0 {
		return 0
	}
	var sc, ss float64
	for _, t := range ts {
		ph := 2 * math.Pi * math.Mod(t, period) / period
		sc += math.Cos(ph)
		ss += math.Sin(ph)
	}
	return math.Hypot(sc, ss) / float64(len(ts))
}

// creditPhaseWindow — длительность замера фазы. Величина выведена из
// требуемого n, а не выбрана «на глаз»: при взводе на tick + uniform[0, tick)
// средний интервал отправок ≈ 12.4 мс, поэтому n ≈ window/12.4мс.
//
// ⚠ Почему НЕ прежние 1200 мс. Там n ≈ 96, шум 1/sqrt(n) = 0.102, а порог
// свойства «решётки нет» — R < 0.2 (hard rule 9), то есть всего 1.96σ. Для
// свободной фазы P(R > r) ≈ exp(−n·r²), значит **2.15 % ложных падений на
// прогон** — при исправном коде. Это и был флейк, уронивший релизный CI на
// v0.3.1. Замерено 2026-09-01: 3 падения на 200 прогонов (1.5 %), все три —
// именно R@8мс = 0.2285 / 0.2121 / 0.2017 при шуме ~0.10, то есть чистый шум,
// перешагнувший фиксированный порог.
//
// При 4 с получается n ≈ 320: 0.2 — это уже 3.6σ, P ≈ 6e−6 на прогон. Порог
// 0.2 НЕ трогаем (он общий с полевым критерием фазы), лечим знаменатель.
const creditPhaseWindow = 4 * time.Second

// minCreditPhaseSends — нижняя граница выборки, ниже которой замер не решает
// НИЧЕГО и обязан упасть громко, а не пройти. При n = 200 порог 0.2 — это
// 2.83σ (P ≈ 3.4e−4), ниже — начинается зона, где красный цвет неотличим от
// шума. Тот самый «зелёный сторож, который ничего не меряет».
const minCreditPhaseSends = 200

// creditPhaseMaxWindow — потолок продления замера. Замер не обрывается по
// creditPhaseWindow, а продлевается, пока не набрано minCreditPhaseSends: иначе
// величина n зависит от загрузки ХОСТА, а не от кода, и тест краснеет по
// причине, к credit-sender'у отношения не имеющей.
//
// Замерено 2026-09-01 на 16 ядрах, фиксированное окно 4 с: без нагрузки
// n = 315…323; при 16 счётных горутинах — 217…244 (медиана интервала растёт
// 12.4 → 16.5 мс); при 32 (двукратная перегрузка) — 114…121; при 48
// (трёхкратная) медиана интервала 56 мс, то есть выборка набирается вчетверо
// дольше номинала.
//
// Потолок 30 с выбран по худшему из замеренных режимов с запасом: при 48
// горутинах продления до 12 с уже НЕ хватало (n = 186…199 против минимума 200 —
// красный впритык, ровно «тест меряет загрузку хоста»). 30 с покрывают
// восьмикратное замедление. Тайм-аут go test (10 мин) не под угрозой: потолок
// достигается только на перегруженном хосте, в норме замер длится 4 с.
//
// ⚠ Продление НЕ маскирует credit-stall, и опирается это не на длину окна:
// сторожем стойла служит ОТНОШЕНИЕ медиан «отправки / контрольный таймер»
// (свойство 3), а оно от длительности замера не зависит вовсе. Проверка выборки
// отвечает только за статистику. Разделение сознательное: пока стойло ловилось
// длиной окна, продление ради медленного хоста напрямую ослабляло бы сторож.
const creditPhaseMaxWindow = 30 * time.Second

// measureCreditSendMoments запускает credit-sender на НАСЫЩЕННОМ потоке и
// возвращает моменты вызова flowSendForTest (секунды от старта замера).
//
// Насыщение самоподдерживающееся: колбэк отправки сам возвращает pendingDelta
// выше creditFlushFloor, поэтому решение «слать» принято на КАЖДОМ пробуждении
// и остаётся ровно момент пробуждения — то есть фаза.
//
// ⚠ Так сделано после замера 2026-09-01, и это не косметика. Прежний харнесс
// подавал кредит внешним time.NewTicker(1мс). Тикеры Go тики не копят, а
// ДРОПАЮТ: под нагрузкой (32 счётных горутины на 16 ядрах) фид проседал до
// ~60 мс, кредита на пробуждении не оказывалось, и n падало 96 → 14…20 —
// 80 падений из 80, причём по посторонней причине («отправок всего 16»).
// Выборка теста не должна зависеть от того, успевает ли ВТОРОЙ тикер.
//
// pendingDelta пополняется прямым атомарным Add, а не через OnStreamConsumed:
// тот берёт streamMu, а колбэк зовётся из creditSenderTick. Сегодня замок там
// уже отпущен (items копируются под ним и обходятся после), но завязываться на
// это из теста не стоит — атомарный путь не сломается, если порядок изменят.
// creditPhaseSample — результат замера: моменты отправок и моменты пробуждений
// КОНТРОЛЬНОГО таймера, крутящегося рядом по тому же расписанию.
//
// Контроль нужен, чтобы сторож credit-stall не превратился в измеритель
// загрузки хоста. Абсолютный порог на интервал отправок этого не позволяет:
// замер 2026-09-01 показал, что исправный код при трёхкратной перегрузке CPU
// даёт медиану интервала 56 мс — всего вчетверо меньше watchdog'а (200 мс), то
// есть любой абсолютный порог между ними ловит нагрузку, а не регресс.
// Контрольный таймер тормозит вместе с хостом, поэтому ОТНОШЕНИЕ медиан
// остаётся ~1 при любой нагрузке и уезжает только когда встаёт сам механизм.
type creditPhaseSample struct {
	sends   []float64 // моменты вызова flowSendForTest
	control []float64 // моменты пробуждений контрольного таймера
}

func measureCreditSendMoments(t *testing.T, window time.Duration) creditPhaseSample {
	t.Helper()

	c := &Client{}
	c.flowControlEnabled = true
	c.flowWindow = 1 << 20
	st := &streamFlowState{window: 1 << 20}
	c.streamFlow = map[uint16]*streamFlowState{9: st}

	// Мьютекс обязателен: flowSendForTest зовётся из горутины credit-sender'а,
	// а слайс читается телом теста. Без него это гонка данных, и замер
	// невалиден, даже если цифра выглядит правдоподобно. На Windows -race
	// недоступен (нет gcc), поэтому зелёный локальный прогон её НЕ покажет —
	// hard rule 6.
	var mu sync.Mutex
	var sends []float64

	start := time.Now()
	c.flowSendForTest = func(streamID uint16, delta uint32) bool {
		elapsed := time.Since(start).Seconds()
		mu.Lock()
		sends = append(sends, elapsed)
		mu.Unlock()
		st.pendingDelta.Add(2 * creditFlushFloor) // самоподпитка насыщения
		return true
	}

	// Контрольный таймер: то же расписание nextCreditSenderWakeup(), тот же
	// планировщик, но без всякой связи с flow control. Его интервалы —
	// «сколько сейчас стоит проснуться на этом хосте».
	var control []float64
	stopCtrl := make(chan struct{})
	go func() {
		ct := time.NewTimer(nextCreditSenderWakeup())
		defer ct.Stop()
		for {
			select {
			case <-stopCtrl:
				return
			case <-ct.C:
				ct.Reset(nextCreditSenderWakeup())
				elapsed := time.Since(start).Seconds()
				mu.Lock()
				control = append(control, elapsed)
				mu.Unlock()
			}
		}
	}()

	st.pendingDelta.Store(2 * creditFlushFloor) // затравка первого тика
	c.startCreditSender()

	// Замер идёт до набора выборки, но не дольше creditPhaseMaxWindow. Опрос
	// раз в 250 мс, а не ожидание ровно window: на загруженном хосте отправки
	// реже, и фиксированное окно превратило бы n в меру загрузки CPU.
	deadline := time.Now().Add(creditPhaseMaxWindow)
	minUntil := time.Now().Add(window)
	for {
		time.Sleep(250 * time.Millisecond)
		mu.Lock()
		got := len(sends)
		mu.Unlock()
		if time.Now().After(deadline) {
			break
		}
		if got >= minCreditPhaseSends && time.Now().After(minUntil) {
			break
		}
	}

	// Останов ДО чтения слайсов. stopCreditSender только закрывает канал и НЕ
	// дожидается выхода горутины (stream_flow.go), поэтому та может дописать
	// ещё одну отметку после возврата — читаем копии под мьютексом, а не
	// полагаемся на «после stop писателя нет».
	c.stopCreditSender()
	close(stopCtrl)
	mu.Lock()
	out := creditPhaseSample{
		sends:   append([]float64(nil), sends...),
		control: append([]float64(nil), control...),
	}
	mu.Unlock()
	return out
}

// intervals — интервалы между соседними моментами, отсортированные.
func intervals(ts []float64) []float64 {
	if len(ts) < 2 {
		return nil
	}
	d := make([]float64, 0, len(ts)-1)
	for i := 1; i < len(ts); i++ {
		d = append(d, ts[i]-ts[i-1])
	}
	sort.Float64s(d)
	return d
}

func quantile(sorted []float64, q float64) float64 {
	if len(sorted) == 0 {
		return 0
	}
	i := int(q * float64(len(sorted)-1))
	return sorted[i]
}

// TestCreditSender_WakeupIsNotAFixedTicker — сторож на ИСТОЧНИК джиттера.
//
// История: этот тест раньше назывался ..._SendPhaseIsQuantizedByTicker и
// фиксировал ДЕФЕКТ — решётку 8 мс, которую тогда ещё не лечили (константу не
// правили по hard rule 8, пока не было доказательства наблюдаемости). После
// замера на проводе 2026-08-19 (payload 71 Б → R@8мс = 0.9445, соседние размеры
// чисты) дефект подтвердился как наблюдаемый и был исправлен: цикл переведён на
// time.Timer с перевзводом на nextCreditSenderWakeup().
//
// Теперь тест сторожит обратное свойство — что период НЕ постоянен. Проверка
// идёт по интервалам, а не по R: разделение с
// TestCreditSender_JitteredWakeupBreaksGrid намеренное — тот отвечает за фазу,
// этот за источник (интервалы обязаны РАЗЛИЧАТЬСЯ, у тикера они равны).
func TestCreditSender_WakeupIsNotAFixedTicker(t *testing.T) {
	if testing.Short() {
		t.Skipf("замер требует ~%s реального времени", creditPhaseWindow)
	}

	// Насыщение здесь ИСКУССТВЕННОЕ (кредит возвращается на каждой отправке,
	// то есть эквивалент десятков МБ/с), и возражение «результат — артефакт
	// насыщения» напрашивается само. Оно проверено и НЕ подтвердилось: замер
	// 2026-08-18 на четырёх скоростях (подвыборка TestCreditRealRates, в дерево
	// не коммичена) дал
	//
	//   0.22 МБ/с (средний в поле) — n=18,  R = 0.9771, интервалы 152-207 мс
	//   1 МБ/с    (p95 интервалов) — n=75,  R = 0.9892, интервалы 32-57 мс
	//   4 МБ/с    (порог за тик)   — n=195, R = 0.9714, интервалы 7-17 мс
	//   20 МБ/с   (пик)            — n=374, R = 0.9574, интервалы 6.5-9.4 мс
	//
	// То есть throughput меняет ЧАСТОТУ отправок, но не их ФАЗУ: каждая
	// отправка всё равно происходит на пробуждении, поэтому при тикере лежит на
	// сетке 8 мс при любой скорости. Решётка сохраняется, редеет только
	// плотность её заполнения.
	sends := measureCreditSendMoments(t, creditPhaseWindow).sends
	if len(sends) < minCreditPhaseSends {
		t.Fatalf("отправок всего %d при минимуме %d — механизм не слал либо хост "+
			"настолько загружен, что замер не решает ничего", len(sends), minCreditPhaseSends)
	}

	const tick = 0.008
	d := intervals(sends)

	// Интервалы между отправками при насыщении. У time.NewTicker они равны
	// периоду с точностью до дрожания планировщика; у jittered-таймера
	// размазаны по [tick, 2*tick).
	//
	// ⚠ Разброс берётся как p95−p05, а НЕ max−min. Max−min ловит одиночный
	// провал планировщика и потому меряет загрузку хоста: под нагрузкой у
	// тикера тоже находились интервалы 1.6 и 18.1 мс (замер 2026-09-01,
	// tools-эксперимент), то есть «разброс» проходил бы порог и при постоянном
	// периоде. Перцентили описывают ФОРМУ распределения, а не его хвост.
	p05, p50, p95 := quantile(d, 0.05), quantile(d, 0.50), quantile(d, 0.95)
	spread := p95 - p05
	t.Logf("отправок n=%d, интервалы p05=%.4fs p50=%.4fs p95=%.4fs min=%.4fs max=%.4fs, разброс(p95-p05)=%.4fs",
		len(sends), p05, p50, p95, d[0], d[len(d)-1], spread)

	// Разброс обязан быть сопоставим с величиной джиттера (до tick). Порог
	// половина тика: у тикера p95−p05 держится в пределах ~1.5 мс даже под
	// нагрузкой, у джиттера это ~7 мс.
	if spread < tick/2 {
		t.Errorf("разброс интервалов %.4f с меньше половины тика — период похож "+
			"на ПОСТОЯННЫЙ. Проверить, не вернулся ли time.NewTicker вместо "+
			"nextCreditSenderWakeup()", spread)
	}

	// Средний интервал обязан превышать сам тик: у постоянного тикера он равен
	// периоду, у джиттерованного — примерно 1.5x. Медиана, а не среднее:
	// среднее тянет вверх любая пауза планировщика, и тогда проверка проходит
	// по причине, к джиттеру отношения не имеющей.
	if p50 < tick*1.15 {
		t.Errorf("медианный интервал %.4f с ≈ тик %.3f с — джиттер не применяется",
			p50, tick)
	}

	// И проверка на источник в исходнике: поведенческие проверки выше остаются
	// зелёными, даже если цикл перестанет звать nextCreditSenderWakeup, а
	// джиттер приедет откуда-то ещё. Тот же приём, что у
	// TestRotationWatchdogLoop_UsesJitteredTimerNotTicker.
	src, err := os.ReadFile("stream_flow.go")
	if err != nil {
		t.Fatalf("чтение stream_flow.go: %v", err)
	}
	body := string(src)
	if strings.Contains(body, "time.NewTicker(creditSenderInterval)") {
		t.Error("в stream_flow.go вернулся time.NewTicker(creditSenderInterval) — " +
			"постоянный период даёт решётку на wire (замерено на проводе)")
	}
	if !strings.Contains(body, "nextCreditSenderWakeup()") {
		t.Error("startCreditSender больше не зовёт nextCreditSenderWakeup()")
	}
}

// TestCreditSender_JitteredWakeupBreaksGrid — сторож на ЛЕЧЕНИЕ фазы.
//
// Решётка 125 Гц была подтверждена на проводе (замер 2026-08-19, pcap: payload
// 71 Б → R@8мс = 0.9445 при n=21 991, соседние размеры чисты). Лечение — то же,
// что применялось к rotationWatchdogTick: Timer с перевзводом на
// tick + uniform[0, tick), джиттер сэмплируется ЗАНОВО каждый взвод.
//
// Тест требует ОБА свойства сразу, потому что починить фазу и незаметно вернуть
// credit-stall — реальный риск: 8 мс выбраны как cheap tick, а из-за задержки
// возврата credits сервер уже вставал в waitForCredit, слот простаивал и его
// жали с close 1006 (см. комментарий creditSenderTick).
//
// ⚠⚠ ГРАНИЦЫ ЭТОГО СТОРОЖА, измерено 2026-09-01 порчей кода — читать до того,
// как считать его зелёный цвет доказательством отсутствия решётки.
//
// ЛОВИТ (проверено порчей, 6 падений из 6): возврат к time.NewTicker —
// исторический дефект, тот самый, что был виден на проводе. R@8мс = 0.9876…
// 0.9920 при шуме 0.082. Это главный регресс, и он закрыт здесь и вторым
// сторожем (TestCreditSender_WakeupIsNotAFixedTicker, проверка исходника).
//
// НЕ ЛОВИТ (проверено порчей, 8 прохождений из 8): `return
// creditSenderInterval` без джиттера, но с сохранённой схемой Timer+Reset.
// R@8мс = 0.006…0.094, то есть шум, тест зелёный.
//
// ⚠ Почему не ловит — важно, потому что напрашивающееся объяснение неверно.
// Дело НЕ в том, что работа creditSenderTick (захват streamMu, обход карты)
// размывает момент вызова колбэка. Измерено прямым экспериментом на четырёх
// конфигурациях (окно 1.2 с, та же машина):
//
//	time.NewTicker(8мс), работы нет        R@8мс = 0.96,  дрейф −0.0 периода
//	time.NewTicker(8мс) + работа 50 мкс    R@8мс = 0.56…0.62
//	Timer+Reset(8мс фикс), работы НЕТ      R@8мс = 0.036, дрейф +9.7 периода
//	Timer+Reset(8мс фикс) + работа 50 мкс  R@8мс = 0.069, дрейф +9.0 периода
//
// То есть Timer+Reset теряет фазу и БЕЗ всякой работы в цикле, а тикер её
// держит ДАЖЕ с работой. Причина — накопление задержки пробуждения: Reset
// отсчитывает период от момента пробуждения, поэтому фактический период равен
// 8 мс + латентность (замер: 8.6 мс), и за прогон фаза линейно проезжает ~10
// периодов. Огибающая такого свипа R ≈ 1/(π·k) при k проехавших периодах:
// 1/(π·9.7) = 0.033, что и наблюдается. time.NewTicker планирует от ПРЕДЫДУЩЕЙ
// точки расписания, а не от пробуждения, поэтому дрейфа не копит.
//
// Следствие, снимающее тревогу: Timer+Reset с фиксированным периодом решётки не
// даёт и НА ПРОВОДЕ — дрейф сидит в самом расписании таймера, а не в задержке
// между пробуждением и отправкой. То есть непойманная порча не является опасным
// регрессом; опасный (тикер) пойман. Но выводить отсюда «джиттер не нужен»
// нельзя: величина дрейфа — это латентность планировщика, она зависит от ОС и
// нагрузки и на быстром Linux-хосте может быть в разы меньше (при 0.08 мс это
// 1.4 периода за прогон → R ≈ 0.23, то есть решётка возвращается). Джиттер
// uniform[0, tick) убирает фазу независимо от хоста — тем и ценен.
//
// ⚠ Чего не доказывает НИ ОДНА из проверок ниже: что решётка наблюдаема
// цензором. Здесь измеряются моменты вызова колбэка внутри процесса, а не уход
// пакета в сеть, — между ними ещё шифрование, WS-фрейминг, TCP и возможная
// коалесценция. Наблюдаемость проверяется только pcap: tools/firstpackets
// -phase (так и был получен замер 2026-08-19, R@8мс = 0.9445 на payload 71 Б).
//
// ⚠ История порогов, чтобы её не переоткрывали. До 2026-09-01 тест был флейки и
// уронил релизный CI на v0.3.1. Причин было две, и обе — «порог зашит константой
// там, где величина зависит от знаменателя»:
//   - порог слепого скана 0.35 при n≈95 лежал ВНУТРИ разброса шума (модель со
//     свободной фазой даёт медиану max R ≈ 0.23, p99 ≈ 0.37); CI поймал 0.3558;
//   - и главное: R < 0.2 при n≈96 — это 1.96σ, то есть 2.15 % ложных падений на
//     прогон при исправном коде. Замер: 3 падения на 200 прогонов, все три с
//     R = 0.2285 / 0.2121 / 0.2017. Красный от шума — не улика.
//
// Лечится знаменателем (окно 4 с → n ≈ 320, порог 0.2 = 3.6σ), а не порогом:
// 0.2 — общий критерий фазы проекта (hard rule 9), и подгонять его под выборку
// значило бы мерить свою ручку.
func TestCreditSender_JitteredWakeupBreaksGrid(t *testing.T) {
	if testing.Short() {
		t.Skipf("замер фазы требует ~%s реального времени", creditPhaseWindow)
	}

	sample := measureCreditSendMoments(t, creditPhaseWindow)
	sends := sample.sends
	if len(sends) < 20 {
		t.Fatalf("отправок всего %d — механизм не слал вовсе, замер невозможен", len(sends))
	}

	// Свойство 3 идёт ПЕРВЫМ намеренно, хотя логически оно последнее. Причина:
	// credit-stall уменьшает число отправок, поэтому проверка выборки ниже
	// сработала бы раньше и объявила бы регресс «недостаточной выборкой» — то
	// есть диагноз был бы снят с механизма и повешен на хост. Отношение медиан
	// осмысленно и на малой выборке, поэтому оно ставит диагноз первым.
	//
	// Регресс, который здесь ловится, — возврат credit-stall: отправки перестают
	// идти на каждом пробуждении (~12 мс) и начинают гейтиться watchdog'ом
	// creditWatchdogNs (200 мс). Именно из-за него сервер вставал в
	// waitForCredit, downlink шёл зубцами, слот простаивал и его жали с
	// close 1006 (см. комментарий creditSenderTick).
	//
	// ⚠⚠ Критерий ОТНОСИТЕЛЬНЫЙ, и это главная правка 2026-09-01. Прежде стояло
	// «max интервал < 50 мс» — абсолютный порог, дефектный дважды:
	//   - max меряет худший провал планировщика, то есть загрузку ХОСТА, а не
	//     механизм: при двукратной перегрузке CPU исправный код давал max
	//     84…90 мс, при трёхкратной медиана доходила до 56 мс. Между 56 мс и
	//     watchdog'ом 200 мс всего 3.5 раза, поэтому ЛЮБОЙ абсолютный порог
	//     между ними на загруженном раннере ловит нагрузку, а не регресс;
	//   - и он был бы недостижим при наборе выборки: n >= 200 означает средний
	//     интервал заведомо меньше — ветка стала бы мёртвой, то есть ровно
	//     «зелёный сторож, который ничего не меряет».
	//
	// Поэтому медиана интервала отправок сравнивается с медианой пробуждений
	// КОНТРОЛЬНОГО таймера, крутящегося рядом по тому же расписанию
	// (creditPhaseSample). Хост тормозит их одинаково, поэтому отношение не
	// зависит от нагрузки: замерено 0.98…1.01 без нагрузки и 1.0…1.2 при
	// трёхкратной перегрузке. При credit-stall уезжают только отправки.
	//
	// Порог 3 стоит между наблюдаемым 1.2 и стойловым >= 3.6 (200/56 — худший
	// случай стойла на трёхкратно перегруженном хосте; на свободном это 16).
	d := intervals(sends)
	ctrl := intervals(sample.control)
	sendMedian, ctrlMedian := quantile(d, 0.50), quantile(ctrl, 0.50)
	t.Logf("интервалы отправок: p50=%.4f p90=%.4f max=%.4f с; контрольный таймер "+
		"p50=%.4f с (n=%d); отношение=%.2f (watchdog %.3f с)",
		sendMedian, quantile(d, 0.90), d[len(d)-1], ctrlMedian, len(ctrl)+1,
		sendMedian/math.Max(ctrlMedian, 1e-9), float64(creditWatchdogNs)/1e9)

	if len(ctrl) < 20 || ctrlMedian <= 0 {
		t.Fatalf("контрольный таймер дал всего %d интервалов — сравнивать не с чем", len(ctrl))
	}
	if ratio := sendMedian / ctrlMedian; ratio > 3 {
		t.Fatalf("credits задержаны: медиана интервала отправок %.4f с при медиане "+
			"пробуждений %.4f с (отношение %.2f > 3). Отправки идут не на каждом "+
			"пробуждении — проверить, не вернулся ли credit-stall (гейт по доле "+
			"окна вместо creditFlushFloor гонит их watchdog'ом %.3f с)",
			sendMedian, ctrlMedian, ratio, float64(creditWatchdogNs)/1e9)
	}

	// Проверка статистической состоятельности для свойств 1 и 2: при меньшей
	// выборке шум 1/sqrt(n) подходит вплотную к порогу 0.2 и красный цвет
	// становится неотличим от случайного. Стойло к этому моменту уже исключено
	// свойством 3, поэтому нехватка выборки означает именно медленный хост.
	if len(sends) < minCreditPhaseSends {
		t.Fatalf("отправок всего %d за %s при минимуме %d — шум 1/sqrt(n) = %.3f "+
			"подходит вплотную к порогу 0.2, замер не решает ничего. Механизм "+
			"при этом исправен (свойство 3 зелёное) — хост перегружен",
			len(sends), creditPhaseMaxWindow, minCreditPhaseSends,
			1/math.Sqrt(float64(len(sends))))
	}

	const tick = 0.008
	r := vectorStrengthPhase(sends, tick)
	noise := 1 / math.Sqrt(float64(len(sends)))
	t.Logf("n=%d R@%.3fs=%.4f шум=%.4f (порог 0.2 = %.1fσ)", len(sends), tick, r, noise, 0.2/noise)

	// Свойство 1: решётки нет. Критерий тот же, что для фазы ротации, — R < 0.2
	// (hard rule 9). Осмыслен он только пока шум заметно ниже порога; это и
	// гарантирует проверка minCreditPhaseSends выше.
	if r >= 0.2 {
		t.Errorf("решётка на периоде тика жива: R = %.4f >= 0.2 (n=%d, шум %.4f). "+
			"Джиттер должен быть на ПЕРИОДЕ пробуждения, а не на пороге", r, len(sends), noise)
	}

	// Свойство 2: слепой скан — линия не переехала на другой масштаб. Именно так
	// провалилась первая попытка лечения watchdog: срезка тика убила линию на
	// 0.2 Гц и подняла пик на 2 Гц.
	//
	// ⚠ Скан ОБЯЗАН обходить окрестность собственного среднего интервала, иначе
	// он меряет не фазу, а шаблон. При взводе на tick + uniform[0, tick) события
	// идут с интервалом 8…16 мс (среднее 12), и на периоде ≈12 мс высокий R
	// получается ДАЖЕ при полностью свободной фазе — это расстояние между
	// событиями, а не решётка. Тот же эффект описан в tools/firstpackets/phase.go
	// («серия с постоянным интервалом даёт „линии нет“ на периоде тика и высокий
	// R в слепом скане на своём интервале»).
	//
	// Цена невыполнения: тест был флейки. Порог 0.35 при n≈95 лежит ВНУТРИ
	// разброса шума — модель со свободной фазой даёт медиану max R ≈ 0.23,
	// p99 ≈ 0.37 и ложное падение в 1.7 % прогонов; CI на v0.3.1 поймал 0.3558
	// на 13 мс при исправном коде. Поэтому порог выводится из шума (как в hard
	// rule 9: «значим только порядок»), а не зашит константой.
	meanInterval := (sends[len(sends)-1] - sends[0]) / float64(len(sends)-1)
	noiseFloor := noise
	// Максимум из ~200 проб шума систематически выше одиночного 1/sqrt(n).
	// 3.5x — эмпирический потолок этого максимума: на 200 прогонах исправного
	// кода наблюдалось отношение max R / шум = 1.2…3.40 (p50 1.72, p90 2.24),
	// ни одного превышения 3.5. Множитель безразмерный, поэтому при росте n
	// порог опускается вместе с шумом и проверка не слабеет.
	scanThreshold := 3.5 * noiseFloor

	bestR, bestP := 0.0, 0.0
	for p := 0.002; p <= 0.100; p += 0.0005 {
		// Окрестность ±25 % вокруг среднего интервала и его первой гармоники —
		// зона, где пик означает шаблон, а не фазу.
		if math.Abs(p-meanInterval) < 0.25*meanInterval ||
			math.Abs(p-2*meanInterval) < 0.25*meanInterval {
			continue
		}
		if rr := vectorStrengthPhase(sends, p); rr > bestR {
			bestR, bestP = rr, p
		}
	}
	t.Logf("слепой скан 2-100 мс (мимо интервала %.4f с): max R=%.4f @ %.4f с, порог %.4f",
		meanInterval, bestR, bestP, scanThreshold)
	if bestR >= scanThreshold {
		t.Errorf("линия переехала на другой период: max R = %.4f @ %.4f с "+
			"при пороге %.4f (шум %.4f, n=%d)", bestR, bestP, scanThreshold, noiseFloor, len(sends))
	}

	// Свойство 3 (credits не задержаны) проверено ВЫШЕ, до проверки выборки —
	// см. объяснение порядка там.
}

// Джиттер thresholdRatio к фазе отправки отношения не имеет: параметр в
// creditSenderTick сохранён для совместимости подписи и порог не гейтит
// (см. комментарий в stream_flow.go:166 `_ = thresholdRatio`). Тест
// фиксирует это, чтобы «джиттер 40-60%» в докстринге startCreditSender не
// читался как защита фазы.
func TestCreditSender_ThresholdRatioDoesNotGateSend(t *testing.T) {
	for _, ratio := range []float64{0.0, 0.4, 0.6, 1.0, 100.0} {
		c := &Client{}
		c.flowControlEnabled = true
		c.flowWindow = 1 << 20
		c.streamFlow = map[uint16]*streamFlowState{3: {window: 1 << 20}}
		c.streamFlow[3].pendingDelta.Store(creditFlushFloor) // ровно порог

		sent := false
		c.flowSendForTest = func(uint16, uint32) bool { sent = true; return true }
		c.creditSenderTick(ratio)

		if !sent {
			t.Fatalf("ratio=%v: не отправлено, хотя pendingDelta == creditFlushFloor; "+
				"значит thresholdRatio ГЕЙТИТ отправку, и докстринг про "+
				"«jittered 40-60%% threshold» описывает живой механизм", ratio)
		}
	}
}
