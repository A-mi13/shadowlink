// инструментирует каждый доступ к памяти, и накладные расходы ложатся
// непропорционально — сильнее всего там, где потоки упираются в один мьютекс.
// Замер контention под -race поэтому мерит стоимость инструментации, а не
// стоимость блокировки (2026-08-10: TestSessionMuContention_NoThroughputCliff
// давал ratio 0.946 без -race и 0.214 под ним, при пороге 0.25 — падение
// целиком объяснялось детектором, код был исправен).
//
// Корректностные тесты гонять под -race нужно всегда; отключать по этому флагу
// стоит ТОЛЬКО тайминговые пороги.
